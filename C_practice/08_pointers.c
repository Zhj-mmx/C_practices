/**
 * 练习8：指针基础（进阶）
 * 练习指针的概念、声明和基本使用
 * 
 * 【超详细注释版——保证初中生也能看懂！】
 * 这个程序会带着你一步步玩转指针，从最简单的“地址”概念，
 * 到稍微复杂一点的动态内存和 const 修饰，统统用生活比喻讲明白。
 */

#include <stdio.h>
#include <stdlib.h>   // 练习5使用 malloc 和 free 必须包含这个头文件，就像借东西要先找到仓库管理员

int main() {
    printf("=== 指针基础练习 ===\n\n");
    
    // ============================================================
    // 练习1: 基本指针概念
    // 比喻：变量是一个“盒子”，值就是盒子里的“东西”。
    //        地址就是盒子的“门牌号”，指针是一张写着门牌号的“纸条”。
    // ============================================================
    printf("1. 基本指针概念:\n");
    
    int var = 42;           // 创建一个叫 var 的盒子，里面放数字 42
    int *ptr = &var;        // 声明一个指针 ptr（纸条），并把 var 的门牌号（&var）写在纸条上
                            // 注意：int *ptr 的意思是 ptr 是用来存放“int 类型盒子”的门牌号
    
    printf("   变量 var 的值: %d\n", var);                 // 看盒子里的东西
    printf("   变量 var 的地址: %p\n", (void*)&var);       // 看 var 盒子的门牌号（%p 专门打印地址）
    printf("   指针 ptr 保存的地址: %p\n", (void*)ptr);    // 看纸条上写的门牌号，和上面一模一样
    printf("   通过指针访问的值 (*ptr): %d\n", *ptr);      // *ptr 的意思是：按照纸条上的门牌号，找到那个盒子，拿出里面的东西
    
    // 纸条的厉害之处：照着纸条不仅能“看”，还能“改”盒子里的东西！
    *ptr = 100;                                 // 按照 ptr 纸条找到 var 盒子，把里面的东西换成 100
    printf("\n   修改 *ptr = 100 后:\n");
    printf("   var 的值现在是: %d\n\n", var);    // 果然，var 盒子里的东西变成 100 了
    
    
    // ============================================================
    // 练习2: 指针与数组
    // 比喻：数组就像一排连续的小柜子，每个柜子都有编号。
    //        数组名就是第一个柜子的门牌号。
    // ============================================================
    printf("2. 指针与数组:\n");
    
    int arr[] = {10, 20, 30, 40, 50};   // 创建一排 5 个柜子，依次放入这些数字
    int *arrPtr = arr;                  // 把第一个柜子的门牌号（arr 本身就代表首地址）写在 arrPtr 纸条上
    
    // 方法一：指针 + 偏移量
    // *(arrPtr + i) 的意思是：从纸条上的门牌号开始，往后数 i 个柜子，拿出里面的东西
    printf("   数组内容: ");
    for (int i = 0; i < 5; i++) {
        printf("%d ", *(arrPtr + i));   // arrPtr+0是第一个，arrPtr+1是第二个……
    }
    printf("\n");
    
    // 方法二：直接把指针当成数组名用（编译器允许这样写）
    // arrPtr[i] 和上面的 *(arrPtr + i) 完全等价，都是拿到第 i 个柜子的东西
    printf("   指针遍历: ");
    for (int i = 0; i < 5; i++) {
        printf("%d ", arrPtr[i]);       // 写法更直观，但本质还是指针
    }
    printf("\n\n");
    
    
    // ============================================================
    // 练习3: 指向指针的指针（二级指针）
    // 比喻：p1 是一张写着 num 门牌号的纸条。
    //        p2 是另一张纸条，上面写的是“p1 那张纸条存放在哪”（即 p1 自己的门牌号）。
    //        所以要找到 num 需要“看两次纸条”：先看 p2 找到 p1，再看 p1 找到 num。
    // ============================================================
    printf("3. 指向指针的指针:\n");
    
    int num = 100;          // 盒子 num，装 100
    int *p1 = &num;         // 纸条 p1，写的是 num 的门牌号
    int **p2 = &p1;         // 纸条 p2，写的是 p1 这张纸条自己的门牌号（注意类型：int **）
    
    printf("   原始值: num = %d\n", num);       // 直接看盒子
    printf("   一级指针: *p1 = %d\n", *p1);     // 看 p1 纸条 → 找到盒子 → 拿出来
    printf("   二级指针: **p2 = %d\n\n", **p2); // 看 p2 纸条 → 找到 p1 纸条 → 再按照 p1 找到盒子 → 拿出来
    
    
    // ============================================================
    // 练习4: 指针作函数参数 —— 交换两个数
    // 以前学过的普通函数传参是“把值复印一份”送进去，改不了原来的盒子。
    // 现在把“门牌号”告诉函数，函数就能直接找到你家的盒子，动手交换里面的东西。
    // ============================================================
    printf("4. 指针作函数参数 - 交换两个数:\n");
    
    void swap(int *a, int *b);      // 函数声明：需要两个“盒子门牌号”作为参数
    int x = 10, y = 20;
    printf("   交换前: x = %d, y = %d\n", x, y);
    swap(&x, &y);                   // 把 x 和 y 的门牌号交给 swap 函数
    printf("   交换后: x = %d, y = %d\n\n", x, y);  // 盒子里的东西真的被互换了！
    
    
    // ============================================================
    // 练习5: 动态内存分配（malloc）
    // 比喻：以前我们用的数组是“在教室里提前摆好固定数量的桌子”，
    //       而 malloc 是“临时去仓库申请搬几张桌子过来”，用完后还可以还回去(free)。
    // ============================================================
    printf("5. 动态内存分配:\n");
    
    int n = 5;
    // 向仓库申请连续的 5 个 int 大小的空间，返回第一个“柜子”的门牌号
    // (int *) 是把仓库返回的“通用门牌号”转成“int 柜子的门牌号”
    int *dynamicArr = (int *)malloc(n * sizeof(int));
    
    // 万一仓库空间不够，申请失败会返回 NULL（空纸条），必须检查！
    if (dynamicArr == NULL) {
        printf("   内存分配失败！\n");
        return 1;
    }
    
    // 和普通数组一样使用这些柜子
    for (int i = 0; i < n; i++) {
        dynamicArr[i] = (i + 1) * 10;    // 填入 10, 20, 30, 40, 50
    }
    
    printf("   动态数组内容: ");
    for (int i = 0; i < n; i++) {
        printf("%d ", dynamicArr[i]);
    }
    printf("\n");
    
    // 非常重要！用完后必须把柜子还给仓库，不然这些柜子永远被占着，别的程序没法用。
    free(dynamicArr);
    printf("   内存已释放\n\n");
    
    
    // ============================================================
    // 练习6: const 指针的区别
    // 这里要区分两种“限制”，记住规则：
    //   const int *p    :  指向“常量”的指针 → 不能通过纸条改盒子里的东西，但纸条可以写别的门牌号
    //   int * const p   :  常量指针           → 纸条本身不能改（永远指着这个盒子），但可以改盒子里的东西
    // ============================================================
    printf("6. const 指针区别:\n");
    
    int a = 10, b = 20;
    const int *ptr1 = &a;   // ptr1 是“指向常量的指针”，盒子 a 被 ptr1 看作“不能改的值”
    int * const ptr2 = &b;  // ptr2 是“常量指针”，它这张纸条终生只能指向 b 这个盒子
    
    printf("   const int *ptr1: 可以改变ptr1指向的地址，但不能通过ptr1修改值\n");
    printf("   int * const ptr2: 可以通过ptr2修改值，但不能改变ptr2指向的地址\n\n");
    
    // 演示 const int *ptr1
    ptr1 = &b;              // ✅ 合法：让 ptr1 纸条改成写 b 的门牌号（纸条内容可以改）
    printf("   ptr1 现在指向 b，*ptr1 = %d\n", *ptr1);
    // *ptr1 = 30;          // ❌ 编译错误：虽然纸条现在指着 b，但法律规定“不能通过这张纸条改值”
    
    // 演示 int * const ptr2
    *ptr2 = 30;             // ✅ 合法：通过 ptr2 纸条找到 b 盒子，把里面的东西改成 30
    printf("   通过 ptr2 修改 b 的值，b 现在 = %d\n", b);
    // ptr2 = &a;           // ❌ 编译错误：ptr2 这张纸条当初写了 b 的门牌号，就一辈子不能改成别的
    
    return 0;
}

// ============================================================
// swap 函数定义
// 参数是两张“纸条”（指针），分别写着两个盒子的门牌号
// 函数内部照着纸条找到盒子，把里面的东西互相交换
// ============================================================
void swap(int *a, int *b) {
    int temp = *a;   // 把 a 纸条对应盒子里的东西暂存到 temp
    *a = *b;         // 把 b 盒子里的东西放到 a 盒子里
    *b = temp;       // 把暂存的东西放到 b 盒子里
}